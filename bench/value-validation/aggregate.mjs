#!/usr/bin/env node
// Value Validation 01 (T81): aggregates detection results (detect.mjs) and agent runs (agent.mjs) into the metrics the
// protocol fixes in advance. Nothing is estimated here: a value that was not measured stays null ("NOT MEASURED").
//   node bench/value-validation/aggregate.mjs --detection <results.json> [--agents <runs.json>] [--markdown <out.md>]
import fs from "node:fs";

const a = process.argv.slice(2);
const arg = (n) => (a.includes(n) ? a[a.indexOf(n) + 1] : undefined);
const read = (f) => (f === undefined ? undefined : JSON.parse(fs.readFileSync(f, "utf8")));

const ratio = (n, d) => (d === 0 ? null : Math.round((n / d) * 1000) / 1000);

/**
 * Primary metric: the blocking judgment (the gate fails CI: ESLint error or check-deps failure; DUO --fail-on block exit
 * 4). A WARN, ASK or UNKNOWN is not a block; it is counted separately so it never turns into a true or false negative.
 * Only cases inside the checker's declared scope are counted; the others are listed as out of scope.
 */
export function confusion(results, checker) {
  const scopeOf = (r) => (checker === "combined" ? (r.scope.eslint === "in" || r.scope.duo === "in" ? "in" : "out") : r.scope[checker]);
  const outcomeOf = (r) => (checker === "combined" ? (r.eslint.outcome === "block" || r.duo.outcome === "block" ? "block" : r.eslint.outcome === "error" || r.duo.outcome === "error" ? "error" : r.duo.outcome) : r[checker].outcome);
  const m = { checker, tp: 0, fp: 0, tn: 0, fn: 0, notBlockingSignal: [], errors: [], outOfScope: [] };
  for (const r of results) {
    const o = outcomeOf(r);
    if (scopeOf(r) !== "in") { m.outOfScope.push({ id: r.id, truth: r.truth, outcome: o }); continue; }
    if (o === "error") { m.errors.push(r.id); continue; }
    if (o === "warn" || o === "ask") m.notBlockingSignal.push({ id: r.id, truth: r.truth, outcome: o });
    const blocked = o === "block";
    if (r.truth === "violation") { if (blocked) m.tp++; else m.fn++; } else if (blocked) m.fp++; else m.tn++;
  }
  const precision = ratio(m.tp, m.tp + m.fp); const recall = ratio(m.tp, m.tp + m.fn);
  return { ...m, precision, recall, f1: precision === null || recall === null || precision + recall === 0 ? null : Math.round((2 * precision * recall / (precision + recall)) * 1000) / 1000, falsePositiveRate: ratio(m.fp, m.fp + m.tn) };
}

/** Per agent run: totals by condition; medians of time and tokens; outcomes against the oracle. */
export function agentSummary(runs) {
  const by = {};
  for (const r of runs) (by[r.condition] ??= []).push(r);
  const med = (xs) => { const v = xs.filter((x) => typeof x === "number").sort((p, q) => p - q); return v.length === 0 ? null : v[Math.floor(v.length / 2)]; };
  const sum = (xs) => { const v = xs.filter((x) => typeof x === "number"); return v.length === 0 ? null : v.reduce((p, q) => p + q, 0); };
  return Object.fromEntries(Object.entries(by).map(([c, rs]) => [c, {
    runs: rs.length, completed: rs.filter((r) => r.status === "completed").length,
    medianWallSeconds: med(rs.map((r) => r.wallSeconds)), totalWallSeconds: sum(rs.map((r) => r.wallSeconds)),
    inputTokens: sum(rs.map((r) => r.usage?.input)), cachedInputTokens: sum(rs.map((r) => r.usage?.cached)), outputTokens: sum(rs.map((r) => r.usage?.output)),
    contextPacketTokens: sum(rs.map((r) => r.duo?.contextTokens)),
    violationsLeft: rs.filter((r) => r.oracle?.violations > 0).length, needsHumanReview: rs.filter((r) => r.oracle?.needsReview === true).length,
    testsPassing: rs.filter((r) => r.tests?.ok === true).length, checkRuns: sum(rs.map((r) => r.events?.checkRuns)), reworkCycles: sum(rs.map((r) => r.events?.reworkCycles)),
    stoppedToAsk: rs.filter((r) => r.oracle?.askedHuman === true).length, proposals: sum(rs.map((r) => r.events?.proposals)),
  }]));
}

function markdown(detection, agents) {
  const out = ["# Value Validation 01 results", "", "Generated by bench/value-validation/aggregate.mjs. Values that were not measured are shown as NOT MEASURED.", ""];
  if (detection !== undefined) {
    out.push("## Deterministic detection (" + detection.results.length + " cases, " + detection.duoctl + ", ESLint " + detection.eslint + ")", "", "| Checker | TP | FP | TN | FN | Precision | Recall | F1 | FP rate | WARN/ASK only | Errors | Out of scope |", "|---|---|---|---|---|---|---|---|---|---|---|---|");
    for (const c of ["eslint", "duo", "combined"]) {
      const m = confusion(detection.results, c);
      const f = (v) => (v === null ? "n/a" : String(v));
      out.push("| " + ({ eslint: "B gate (ESLint + check-deps)", duo: "DUO alone", combined: "C gate (B + DUO)" })[c] + " | " + [m.tp, m.fp, m.tn, m.fn, f(m.precision), f(m.recall), f(m.f1), f(m.falsePositiveRate)].join(" | ") + " | " + (m.notBlockingSignal.map((x) => x.id + " " + x.outcome).join(", ") || "-") + " | " + (m.errors.join(", ") || "-") + " | " + (m.outOfScope.map((x) => x.id + " " + x.outcome).join(", ") || "-") + " |");
    }
    out.push("", "| Case | Category | Rule | Truth | B gate | DUO | DUO claims |", "|---|---|---|---|---|---|---|");
    for (const r of detection.results) out.push("| " + [r.id, r.category, r.rule, r.truth, r.eslint.outcome + (r.scope.eslint === "out" ? " (out of scope)" : ""), r.duo.outcome + (r.scope.duo === "out" ? " (out of scope)" : ""), r.duo.claims.map((c) => c.rule + " " + c.alignment + (c.provenance ? " " + c.provenance : "")).join("; ") || "-"].join(" | ") + " |");
    const ms = (k) => detection.results.map((r) => r[k].ms).sort((p, q) => p - q);
    out.push("", "Checker time per case (median ms): B gate " + ms("eslint")[Math.floor(detection.results.length / 2)] + ", DUO review with --refresh " + ms("duo")[Math.floor(detection.results.length / 2)] + ".", "");
  }
  if (agents !== undefined) {
    out.push("## Agent runs", "", "| Condition | Runs | Completed | Median wall s | Input tokens | Cached input | Output tokens | Context Packet tokens | Runs with violations left | Needs human review | Tests passing | Check runs | Rework cycles | Stopped to ask | Proposals |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
    const f = (v) => (v === null || v === undefined ? "NOT MEASURED" : String(v));
    for (const [c, s] of Object.entries(agentSummary(agents.runs))) out.push("| " + [c, s.runs, s.completed, s.medianWallSeconds, s.inputTokens, s.cachedInputTokens, s.outputTokens, s.contextPacketTokens, s.violationsLeft, s.needsHumanReview, s.testsPassing, s.checkRuns, s.reworkCycles, s.stoppedToAsk, s.proposals].map(f).join(" | ") + " |");
    out.push("");
  }
  return out.join("\n");
}

const detection = read(arg("--detection"));
const agents = read(arg("--agents"));
const md = markdown(detection, agents);
if (arg("--markdown") !== undefined) fs.writeFileSync(arg("--markdown"), md);
console.log(md);
